#!/usr/bin/env python3
"""Detective control for repos whose plan cannot enforce branch protection.

Fails when the head commit of a push to the default branch is not the product of
a merged pull request whose head commit had green checks. It detects after the
fact; it does not prevent. Stdlib only so any repo can run it with the runner's
python.

Checks are read from the pull request's head commit, not from the pushed commit:
a squash or rebase merge creates a new commit whose only check runs are the
sibling push workflows (deploys, this job) that are still in progress.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import time

_GREEN = {"success", "skipped", "neutral"}
_SELF = "main-integrity"
# Subjects the fleet's release tooling really writes (observed 2026-10-14):
#   chore: release v1.13.0            (python-semantic-release, with body below)
#   1.18.0                            (python-semantic-release default, with body)
#   chore(release): v3.19.2           (semantic-release, no body)
#   fix(release): v1.36.0 [skip ci]   (CI release bot, no body)
_VERSION = r"\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?"
_RELEASE_SUBJECT = re.compile(
    rf"^(?:(?:chore|fix|feat)(?:\(release\))?: (?:release )?v{_VERSION}|{_VERSION})"
    r"(?: \[skip ci\])?$")
_RELEASE_BODY = "Automatically generated by python-semantic-release"
# A subject alone is trivially typed by a person, so it needs a second witness:
# the tool's body text, or a committer identity that only the release job uses.
# Neither is unforgeable; the control exists to catch an accidental direct push,
# not to stop someone who is deliberately forging release commits.
_RELEASE_COMMITTERS = frozenset({"semantic-release", "n24q02m-ci", "github-actions[bot]"})


def exempt(message: str, committer: str = "") -> bool:
    """True for a commit made by the release tooling, which never has a pull request."""
    subject, _, body = (message or "").partition("\n")
    if _RELEASE_SUBJECT.match(subject.strip()) is None:
        return False
    return _RELEASE_BODY in body or (committer or "").strip().lower() in _RELEASE_COMMITTERS


def _merged(pulls: list[dict], branch: str | None) -> list[dict]:
    """Merged pull requests, narrowed to those that targeted `branch` when it is given.

    A pull request merged into some other branch says nothing about commits that
    later reach the default branch, so it must not vouch for them.
    """
    merged = [p for p in pulls if p.get("merged_at")]
    if branch:
        merged = [p for p in merged if (p.get("base") or {}).get("ref") == branch]
    return merged


def check(sha: str, pulls: list[dict], check_runs: list[dict],
          branch: str | None = None) -> tuple[bool, str]:
    merged = _merged(pulls, branch)
    if not merged:
        return False, f"{sha[:8]}: no merged pull request is associated with this commit"
    runs = [r for r in check_runs if r.get("name") != _SELF]
    if not runs:
        return False, f"{sha[:8]}: pull request #{merged[0].get('number')} has no check runs"
    bad = []
    for run in runs:
        if run.get("status") != "completed":
            bad.append(f"{run.get('name')}: {run.get('status')}")
        elif run.get("conclusion") not in _GREEN:
            bad.append(f"{run.get('name')}: {run.get('conclusion')}")
    if bad:
        return False, f"{sha[:8]}: checks not green: " + "; ".join(bad)
    return True, f"{sha[:8]}: merged via #{merged[0].get('number')} with green checks"


def _gh(path: str) -> object:
    out = subprocess.run(
        ["gh", "api", path, "-H", "Accept: application/vnd.github+json"],
        capture_output=True, text=True, check=True,
    ).stdout
    return json.loads(out)


def _pulls_for(repo: str, sha: str, gh=None, sleep=time.sleep,
               attempts: int = 4, delay: float = 5.0) -> list[dict]:
    """Pull requests linked to a commit; GitHub links a fresh merge a moment late."""
    gh = gh or _gh
    pulls: list[dict] = []
    for attempt in range(attempts):
        data = gh(f"repos/{repo}/commits/{sha}/pulls")
        pulls = data if isinstance(data, list) else []
        if pulls or attempt == attempts - 1:
            break
        sleep(delay)
    return pulls


def _check_runs(repo: str, sha: str, gh=None) -> list[dict]:
    """Every check run of a commit; a large matrix spans more than one 100-run page."""
    gh = gh or _gh
    runs: list[dict] = []
    page = 1
    while True:
        data = gh(f"repos/{repo}/commits/{sha}/check-runs?per_page=100&page={page}")
        batch = data.get("check_runs", []) if isinstance(data, dict) else []
        runs.extend(batch)
        total = data.get("total_count", 0) if isinstance(data, dict) else 0
        if len(batch) < 100 or len(runs) >= total:
            return runs
        page += 1


def _merged_pull(sha: str, pulls: list[dict], branch: str | None = None) -> dict | None:
    merged = _merged(pulls, branch)
    exact = [p for p in merged if p.get("merge_commit_sha") == sha]
    return (exact or merged or [None])[0]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", required=True)
    parser.add_argument("--sha", required=True)
    parser.add_argument("--branch", default=os.environ.get("GITHUB_REF_NAME") or None,
                        help="branch that was pushed; only pull requests merged into it "
                             "count (defaults to GITHUB_REF_NAME)")
    args = parser.parse_args()
    commit = _gh(f"repos/{args.repo}/commits/{args.sha}")
    detail = (commit.get("commit") or {}) if isinstance(commit, dict) else {}
    message = detail.get("message", "")
    committer = (detail.get("committer") or {}).get("name", "")
    if exempt(message, committer):
        print(f"{args.sha[:8]}: exempt release-tooling commit")
        return 0
    pulls = _pulls_for(args.repo, args.sha)
    pull = _merged_pull(args.sha, pulls, args.branch)
    runs: list[dict] = []
    if pull is not None:
        head = (pull.get("head") or {}).get("sha")
        if head:
            runs = _check_runs(args.repo, head)
    ok, why = check(args.sha, pulls, runs, args.branch)
    print(why)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
